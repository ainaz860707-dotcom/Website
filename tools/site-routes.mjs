export function pickRoute(input) {
  const text = String(input ?? '').trim().toLowerCase();
  if (!text) throw new Error('маршрут не выбрать: описание бизнеса пустое');

  for (const key of ORDER) {
    const route = ROUTES[key];
    const hit = text.match(route.marks);
    if (hit) return { key, route, why: `сработало «${hit[0]}»` };
  }

  return {
    key: 'usluga-ryadom',
    route: ROUTES['usluga-ryadom'],
    why: 'ни одного признака не сработало, взят маршрут по умолчанию',
  };
}

export function structureBlock(route) {
  return `${route.sections.map((s, i) => `${i + 1}. ${s}`).join('\n')}\n\n${COMMON}`;
}

export function routeBlock({ key, route, why }) {
  return `ТИП САЙТА: ${route.name} (${key}) — ${why}.
Разметка JSON-LD: ${route.schema.join(' + ')}.
Кадры: ${route.media.kinds.join(' · ')}${route.media.gallery ? '; галерея обязательна' : ''}.`;
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) {
  const input = process.argv.slice(2).join(' ').trim();
  if (!input) {
    process.stdout.write('\nмаршруты:\n');
    for (const [key, r] of Object.entries(ROUTES)) {
      process.stdout.write(`  ${key.padEnd(16)} ${r.name} — ${r.who}\n`);
    }
    process.stdout.write('\nиспользование: node tools/site-routes.mjs <описание бизнеса>\n\n');
    process.exit(0);
  }

  const picked = pickRoute(input);
  process.stdout.write(`${routeBlock(picked)}\n\nСТРУКТУРА:\n${structureBlock(picked.route)}\n`);
}
