export function pickDirection(input, id) {
  const text = input.toLowerCase();
  const hit = DIRECTIONS.find((d) => d.niches.some((n) => text.includes(n)));
  return hit ?? DIRECTIONS[(Number(id) || 0) % DIRECTIONS.length];
}
